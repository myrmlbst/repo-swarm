/**
 * Small inline icon set (24x24 outline glyphs, stroke inherits currentColor)
 * so the app needs no icon-font or image requests. All are decorative:
 * `aria-hidden` is set here, so the adjacent visible text — never the icon —
 * carries the meaning for assistive tech.
 */
type IconProps = { className?: string };

function Outline({ className, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {children}
    </svg>
  );
}

